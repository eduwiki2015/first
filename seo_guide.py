NAVER_SEO_GUIDE = """
## 네이버 블로그 상위노출 작성 기준 (반드시 준수)

### 제목
- 핵심 키워드를 제목의 앞쪽에 배치한다.
- 제목 길이는 공백 포함 20~32자 사이로 한다.
- 특수문자 남용 금지. 낚시성 제목 금지. 키워드는 제목에 1회만 사용한다.

### 본문 구조
- 전체 분량은 공백 제외 1,500~2,500자로 한다.
- 첫 문단(도입부)에 핵심 키워드를 자연스럽게 1회 포함하고, 글이 어떤 내용인지 명확히 알려준다.
- 소제목을 3~5개 사용해 본문을 구획한다. 소제목 일부에는 핵심 키워드 또는 연관 키워드를 넣는다.
- 문단은 3~5문장 단위로 짧게 끊는다. 모바일 가독성을 우선한다.
- 마지막 문단에서 내용을 요약하고, 독자의 다음 행동(댓글, 이웃추가, 관련 글)을 유도한다.

### 키워드 사용
- 핵심 키워드는 본문 전체에 5~8회 자연스럽게 분산 배치한다. (억지 반복 금지 — 어뷰징으로 분류됨)
- 핵심 키워드의 유사어·연관 키워드를 2~3개 함께 사용한다.
- 동일 문장/문구를 반복하지 않는다.

### 신뢰도 신호 (D.I.A. — 경험·전문성)
- 실제 경험한 것처럼 구체적인 디테일(수치, 상황, 과정, 느낀 점)을 포함해 서술한다.
- 정보성 글이라면 근거와 구체적 정보(가격, 위치, 방법, 순서 등)를 명확히 제시한다.
- 광고티가 나는 표현("최고", "무조건", 과도한 감탄사 반복)을 피한다.

### 이미지
- 본문 중 이미지가 들어가면 좋은 위치에 `[이미지: 어떤 사진을 넣을지 설명]` 형태로 표시한다.
- 이미지 권장 개수는 3~7장. 도입부 직후, 각 소제목 아래에 배치한다.

### 태그
- 태그는 5~10개 제안한다. 핵심 키워드, 연관 키워드, 카테고리성 키워드를 섞는다.
- 본문 내용과 무관한 인기 태그를 넣지 않는다.
""".strip()

NAVER_CAFE_GUIDE = """
## 네이버 카페 글 상위노출 작성 기준 (반드시 준수)

카페 글은 블로그와 노출 방식이 다르다. 커뮤니티 성격이 강하고, 정보성·후기성
글이 회원들의 반응(댓글, 조회)을 얻을 때 통합검색 카페탭에서 잘 노출된다.

### 제목
- 핵심 키워드를 제목 앞쪽에 배치한다. 제목은 15~30자.
- 실제 회원이 쓴 것처럼 자연스럽고 궁금증을 유발하는 제목으로 한다.
- 과한 광고성 제목("최고", "강추" 남발)은 피한다.

### 본문 구조
- 분량은 공백 제외 800~1,800자로 한다. (블로그보다 짧아도 된다)
- 첫 문단에서 핵심 키워드를 자연스럽게 1회 포함하고, 어떤 글인지 알린다.
- 소제목은 2~4개. 카페는 블로그보다 격식이 덜하므로 문단 구분 위주로 해도 된다.
- 실제 경험·후기처럼 구어체와 솔직한 톤을 섞는다. (딱딱한 정보 나열보다 대화체가 유리)
- 마지막에 질문을 던지거나 의견을 구해 댓글 반응을 유도한다.

### 키워드 사용
- 핵심 키워드는 본문에 4~6회 자연스럽게 분산한다. (억지 반복 금지)
- 연관 키워드 2~3개를 함께 사용한다.

### 신뢰도·반응 신호
- 실제 회원 후기처럼 구체적 경험(수치, 상황, 느낀 점)을 넣는다.
- 지나친 홍보·상업적 표현은 카페에서 제재되기 쉬우니 정보 제공 위주로 쓴다.

### 이미지
- 이미지가 들어갈 위치에 `[이미지: 어떤 사진을 넣을지 설명]` 형태로 표시한다.
- 카페 글은 2~5장 권장.

### 태그
- 태그는 3~7개 제안한다. (카페는 블로그보다 태그 비중이 낮다)
""".strip()


def get_guide(content_type: str = "blog") -> str:
    """content_type: 'blog' 또는 'cafe' 에 맞는 상위노출 기준을 반환."""
    return NAVER_CAFE_GUIDE if content_type == "cafe" else NAVER_SEO_GUIDE


